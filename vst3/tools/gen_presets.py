#!/usr/bin/env python3
"""Generates src/core/gen/presets.inc from tools/registrations.json
(the 40 registrations of the manual, pages 84-93, transcribed from the red marks).

Slider positions in the JSON: 0 = bottom end of the printed line, 10 = top end -> normalized value / 10.
Controls without a red mark (null) are not used by the sound: they get the parameter default.
Run:  python3 vst3/tools/gen_presets.py
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src', 'core')

# parameter ids and defaults from params.h / params.cpp (parsed, so there is only one source)
ids = re.findall(r'^\s+(P_[A-Z0-9_]+)(?: = 0)?,', open(os.path.join(SRC, 'params.h')).read(), re.M)
ids = ids[:ids.index('P_COUNT')] if 'P_COUNT' in ids else ids
defs = {}
for m in re.finditer(r'\{ (P_[A-Z0-9_]+), "[^"]*", "[^"]*", Kind::\w+, (\w+(?: - 1)?), ([0-9.]+),', open(os.path.join(SRC, 'params.cpp')).read()):
    defs[m.group(1)] = float(m.group(3))
assert len(defs) == len(ids), (len(defs), len(ids))

SLIDERS = {
    'mono_tuning': 'P_MONO_TUNING', 'mono_volume': 'P_MONO_VOLUME', 'vib_depth': 'P_VIB_DEPTH', 'vib_speed': 'P_VIB_SPEED',
    'porta_timer': 'P_PORTA_TIME', 'vcf_adsr': 'P_VCF_ADSR', 'vcf_osc': 'P_VCF_OSC', 'vcf_bias': 'P_VCF_BIAS',
    'vcf_emphasis': 'P_VCF_EMPH', 'attack': 'P_ATTACK', 'decay': 'P_DECAY', 'sustain': 'P_SUSTAIN', 'release': 'P_RELEASE',
    'vca_adsr': 'P_VCA_ADSR', 'vca_osc': 'P_VCA_OSC', 'poli_volume': 'P_POLI_VOLUME', 'poli_brilliance': 'P_POLI_BRILL',
    'str_volume': 'P_STR_VOLUME', 'str_brilliance': 'P_STR_BRILL', 'str_sustain': 'P_STR_SUSTAIN', 'str_attack': 'P_STR_ATTACK',
}
MONO = ['TUBA', 'TROMBONE', 'TRUMPET', 'SAX', 'CLARINET', 'OBOE', 'FLUTE', 'PICCOLO', 'VIOLIN', 'ACCORDION', 'EL_BASS', 'EL_GUITAR']
POLI = ['PIANO', 'HARPSICHORD', 'HONKY_TONK', 'BRASS', 'BRASS_VIBRATO']
TOGGLES = {'FREE': 'P_FREE', 'POLI_STRINGS_IN_MONO': 'P_POLI_IN_MONO', 'SPLIT_KEYBOARD': 'P_SPLIT', 'STRINGS_8': 'P_STRINGS_8',
           'STRINGS_4': 'P_STRINGS_4', 'MONO_BRILL': 'P_TOUCH_MONO_BRILL', 'OSCILL': 'P_TOUCH_OSCILL',
           'MONO_GLIDE': 'P_TOUCH_MONO_GLIDE', 'BRASS_BRILL': 'P_TOUCH_BRASS_BRILL'}
OSC_MODES = ['adsr', 'release', 'attack', 'continuous']

regs = json.load(open(os.path.join(HERE, 'registrations.json')))
out = ['// generated by tools/gen_presets.py from tools/registrations.json - do not edit', '']
for r in regs:
    v = dict(defs)
    for k, val in r['sliders'].items():
        if val is not None:
            v[SLIDERS[k]] = round(max(0.0, min(10.0, val)) / 10.0, 4)
    v['P_MONO_TUNING'] = 0.5
    v['P_POLI_PITCH'] = 0.5 if r.get('poli_pitch') is None else 0.5 + 0.5 * r['poli_pitch']
    tabs = r['tabs']
    mono = [t for t in tabs if t in MONO]
    poli = [t for t in tabs if t in POLI]
    v['P_MONO_REG'] = (MONO.index(mono[0]) + 1) / 12.0 if mono else 0.0
    # registration 4 shows BRASS and BRASS VIBRATO together: the vibrato tab wins (it includes the brass timbre)
    p = 'BRASS_VIBRATO' if 'BRASS_VIBRATO' in poli else (poli[0] if poli else None)
    v['P_POLI_REG'] = (POLI.index(p) + 1) / 5.0 if p else 0.0
    for t, pid in TOGGLES.items():
        v[pid] = 1.0 if t in tabs else 0.0
    v['P_OSC_ON'] = 1.0 if r.get('osc_on') else 0.0
    v['P_PORTA_ON'] = 1.0 if r.get('porta_on') else 0.0
    v['P_LFO_WAVE'] = 0.0 if r.get('osc_wave') == 'square' else 1.0
    mode = r.get('osc_mode') or 'continuous'
    v['P_OSC_MODE'] = OSC_MODES.index(mode) / 3.0
    v['P_ENV_TRIGGER'] = {'off': 0.0, 'trigger': 0.5, 'phaser': 1.0}.get(r.get('eft', 'off'), 0.0)
    vals = ', '.join(f'{v[i]:.4g}' for i in ids)
    name = r['name'].replace('"', "'")
    out.append(f'{{ "{name}", {{ {vals} }} }},')
os.makedirs(os.path.join(SRC, 'gen'), exist_ok=True)
open(os.path.join(SRC, 'gen', 'presets.inc'), 'w').write('\n'.join(out) + '\n')
print(f'{len(regs)} registrations -> src/core/gen/presets.inc ({len(ids)} parameters)')
